def решить(заказ: dict) -> dict:
    позиции = заказ.get("позиции") or []
    сумма = 0
    дефицит = []
    for п in позиции:
        кол = п["кол"]
        сумма += кол * п["цена"]
        if кол > п["остаток"]:
            дефицит.append(п["товар"])
    сумма = int(round(сумма))
    return {
        "сумма": сумма,
        "маршрут": "ждать_менеджера" if сумма > 200000 else "резерв",
        "дефицит": дефицит,
    }