ЛЕКСЕМА = re.compile(r'\s*(?:(\d+(?:\.\d+)?)|("[^"]*")|([A-Za-zА-Яа-яЁё_][\wА-Яа-яЁё]*)|(>=|<=|==|!=|[-+*/()<>,=\[\]]))')
