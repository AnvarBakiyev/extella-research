#!/usr/bin/env python3
"""Замер «навык против эксперта» на Claude через агента Extella (20.10.2026).

Копия zamer.py от 27.09 с заменённой функцией вызов(): вместо Ollama — POST /api/agent/run
агента zamer-claude (без инструментов, короткий системный промпт). Счётчики токенов берутся
из usage.input_tokens / usage.output_tokens ответа платформы (формат Responses), это точные
числа от Anthropic, не оценка. Во вход каждого вызова входит системный промпт агента (~300 ток.).
Запуск: python3 zamer_claude.py sonnet|opus  (модель переключается у агента заранее).
"""
import json, re, time, urllib.request, sys, traceback, os

МЕТКА = sys.argv[1] if len(sys.argv) > 1 else "sonnet"
МОДЕЛЬ = {"sonnet": "claude-sonnet-5-5", "opus": "claude-opus-5-5"}[МЕТКА] + " (агент zamer-claude, effort low)"
АГЕНТ = "<agent id>"
ТОКЕН = open(os.path.expanduser("~/.extella/api_token.txt")).read().strip()
ПАПКА = "<this folder>"
ЗАКАЗЫ = json.load(open(f"{ПАПКА}/dataset.json", encoding="utf-8"))
НАВЫК = """Ты — модуль согласования заказов. На вход приходит заказ в JSON: id, клиент, позиции; у каждой позиции: товар, кол, цена, остаток.
Правила:
1. Сумма заказа = сумма по всем позициям (кол × цена).
2. Если сумма больше 200000 — маршрут "ждать_менеджера", иначе "резерв".
3. Позиция в дефиците, если кол больше остатка. Перечисли товары таких позиций в порядке следования.
Ответь строго одним JSON-объектом без пояснений и без markdown:
{"сумма": <целое число>, "маршрут": "<ждать_менеджера|резерв>", "дефицит": [<товары>]}"""

def вызов(промпт, num_predict=300):
    t0 = time.time()
    тело = {"agent_id": АГЕНТ, "input": промпт, "max_output_tokens": num_predict, "store": False, "run_timeout": 180}
    req = urllib.request.Request("https://api.extella.ai/api/agent/run", data=json.dumps(тело).encode(),
        headers={"Content-Type": "application/json", "X-Auth-Token": ТОКЕН, "X-Profile-Id": "default", "X-Agent-Id": АГЕНТ})
    for попытка in range(6):
        try:
            r = json.load(urllib.request.urlopen(req, timeout=240)); break
        except urllib.error.HTTPError as e:
            if e.code != 429 or попытка == 5: raise
            пауза = int(e.headers.get("Retry-After") or 0) or 15 * (попытка + 1)
            print(f"  (429, жду {пауза} с)", flush=True); time.sleep(пауза)
        except Exception as e:
            if попытка == 5: raise
            print(f"  (повтор вызова: {str(e)[:80]})", flush=True); time.sleep(5)
    time.sleep(1.5)  # пауза между вызовами, чтобы не упираться в лимит запросов
    текст = "".join(c.get("text", "") for o in r.get("output", []) if o.get("type") == "message" for c in o.get("content", []))
    u = r.get("usage") or {}
    return текст, u.get("input_tokens", 0), u.get("output_tokens", 0), time.time() - t0

def разобрать_json(текст):
    m = re.search(r"\{.*\}", текст, re.S)
    if not m: return None
    try: return json.loads(m.group(0))
    except Exception: return None

def совпало(ответ, эталон):
    if not isinstance(ответ, dict): return False
    try:
        return (int(ответ.get("сумма")) == эталон["сумма"]
                and ответ.get("маршрут") == эталон["маршрут"]
                and list(ответ.get("дефицит", [])) == эталон["дефицит"])
    except Exception:
        return False

def заказ_без_эталона(з):
    return {k: v for k, v in з.items() if k != "эталон"}

итог = {"модель": МОДЕЛЬ, "навык": {"прогоны": []}, "эксперт": {"попытки": []}, "детерминизм": {}}

# ---------- Сторона «эксперт»: создание кода ----------
print("== ЭКСПЕРТ: создание кода", flush=True)
промпт = (НАВЫК + "\n\nНапиши функцию на Python с сигнатурой `def решить(заказ: dict) -> dict`, "
          "реализующую эти правила и возвращающую такой же объект. Только код, без пояснений, без примеров.")
код_готов = None
for попытка in range(1, 4):
    текст, вх, вых, сек = вызов(промпт, num_predict=800)
    m = re.search(r"```(?:python)?\s*(.*?)```", текст, re.S)
    код = (m.group(1) if m else текст).strip()
    пространство = {}
    ошибки = 0; первая_ошибка = None
    try:
        exec(код, пространство)
        f = пространство["решить"]
        for з in ЗАКАЗЫ:
            try:
                if not совпало(f(заказ_без_эталона(з)), з["эталон"]):
                    ошибки += 1
                    if первая_ошибка is None: первая_ошибка = (з["id"], f(заказ_без_эталона(з)), з["эталон"])
            except Exception as e:
                ошибки += 1
                if первая_ошибка is None: первая_ошибка = (з["id"], f"исключение: {e}", з["эталон"])
    except Exception as e:
        ошибки = len(ЗАКАЗЫ); первая_ошибка = ("компиляция", traceback.format_exc()[-400:], None)
    итог["эксперт"]["попытки"].append({"попытка": попытка, "вход": вх, "выход": вых, "сек": round(сек, 1),
                                        "ошибок_из_100": ошибки, "код": код})
    print(f"  попытка {попытка}: вход {вх}, выход {вых}, {сек:.0f} c, ошибок {ошибки}/100", flush=True)
    if ошибки == 0:
        код_готов = код; break
    промпт = (НАВЫК + "\n\nТвой предыдущий код:\n```python\n" + код + "\n```\nОн даёт неверный результат. "
              f"Пример: заказ {первая_ошибка[0]} → твой ответ {первая_ошибка[1]}, ожидалось {первая_ошибка[2]}. "
              "Исправь и верни только код функции `решить`.")
итог["эксперт"]["код_прошёл_эталон"] = код_готов is not None
итог["эксперт"]["токены_создания"] = sum(p["вход"] + p["выход"] for p in итог["эксперт"]["попытки"])

# ---------- Сторона «эксперт»: сто прогонов кода без модели ----------
if код_готов:
    пространство = {}; exec(код_готов, пространство); f = пространство["решить"]
    t0 = time.time()
    for _ in range(100):
        for з in ЗАКАЗЫ: f(заказ_без_эталона(з))
    итог["эксперт"]["сек_на_100_прогонов_по_100_заказам"] = round(time.time() - t0, 3)
    open(f"{ПАПКА}/expert_code_claude_{МЕТКА}.py", "w", encoding="utf-8").write(код_готов)

# ---------- Сторона «навык»: сто прогонов через модель ----------
print("== НАВЫК: 100 прогонов", flush=True)
for i, з in enumerate(ЗАКАЗЫ, 1):
    текст, вх, вых, сек = вызов(НАВЫК + "\n\nЗаказ:\n" + json.dumps(заказ_без_эталона(з), ensure_ascii=False))
    ответ = разобрать_json(текст)
    ок = совпало(ответ, з["эталон"])
    итог["навык"]["прогоны"].append({"id": з["id"], "вход": вх, "выход": вых, "сек": round(сек, 1), "верно": ок,
                                     "ответ": ответ, "сырой": текст[:300]})
    if i % 10 == 0:
        верных = sum(1 for p in итог["навык"]["прогоны"] if p["верно"])
        print(f"  {i}/100 · верных {верных} · токены вход {sum(p['вход'] for p in итог['навык']['прогоны'])} "
              f"выход {sum(p['выход'] for p in итог['навык']['прогоны'])}", flush=True)
        json.dump(итог, open(f"{ПАПКА}/results_claude_{МЕТКА}.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)

# ---------- Детерминизм: те же первые 10 заказов второй раз ----------
print("== ДЕТЕРМИНИЗМ: повтор первых 10", flush=True)
расхождений = 0
for з in ЗАКАЗЫ[:10]:
    текст, *_ = вызов(НАВЫК + "\n\nЗаказ:\n" + json.dumps(заказ_без_эталона(з), ensure_ascii=False))
    первый = next(p for p in итог["навык"]["прогоны"] if p["id"] == з["id"])["ответ"]
    if разобрать_json(текст) != первый: расхождений += 1
итог["детерминизм"] = {"повторено": 10, "ответ_изменился": расхождений}

json.dump(итог, open(f"{ПАПКА}/results_claude_{МЕТКА}.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
н = итог["навык"]["прогоны"]
print("\n== ИТОГ")
print(f"навык: {sum(p['вход'] for p in н)} вход + {sum(p['выход'] for p in н)} выход токенов на 100 прогонов; "
      f"верных {sum(1 for p in н if p['верно'])}/100; среднее {sum(p['сек'] for p in н)/len(н):.1f} c/прогон")
print(f"эксперт: {итог['эксперт']['токены_создания']} токенов на создание ({len(итог['эксперт']['попытки'])} попыт.), "
      f"прошёл эталон: {итог['эксперт']['код_прошёл_эталон']}; "
      f"10 000 прогонов кода: {итог['эксперт'].get('сек_на_100_прогонов_по_100_заказам')} c")
print(f"детерминизм навыка: изменилось {расхождений} из 10 повторов")
