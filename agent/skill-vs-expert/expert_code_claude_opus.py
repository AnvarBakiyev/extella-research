def решить(заказ: dict) -> dict:
    позиции = заказ.get("позиции", []) or []
    сумма = 0
    дефицит = []
    for п in позиции:
        кол = п.get("кол", 0) or 0
        цена = п.get("цена", 0) or 0
        остаток = п.get("остаток", 0) or 0
        сумма += кол * цена
        if кол > остаток:
            дефицит.append(п.get("товар"))
    сумма_целая = int(round(сумма))
    маршрут = "ждать_менеджера" if сумма > 200000 else "резерв"
    return {"сумма": сумма_целая, "маршрут": маршрут, "дефицит": дефицит}