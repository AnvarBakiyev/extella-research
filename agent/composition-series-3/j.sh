#!/bin/sh
# j.sh <python|extella> <сценарий> <текст> — запись в журнал стороны с отметкой времени
f="$(dirname "$0")/zhurnal-$1-stek.md"; [ -f "$f" ] || printf "# Журнал стороны %s (серия 2, части 3–4)\n\n| время | сценарий | запись |\n|---|---|---|\n" "$1" > "$f"
printf "| %s | %s | %s |\n" "$(date '+%d.%m %H:%M:%S')" "$2" "$3" >> "$f"
